func nativeMarkerFixture(ttl TTL) (cpaUsageFixture, NativeCredential) {
	n, c := nativeFixture()
	n.CachePolicy.Selected.TTL = string(ttl)
	n.CachePolicy.EffectiveTTL = string(ttl)
	n.TokenBreakdown.Input.CacheWriteTokens = 100
	n.TokenBreakdown.Input.TotalTokens = 400
	n.TokenBreakdown.TotalTokens = 700
	n.Detail.CacheCreationTokens = 100
	n.Detail.TotalTokens = 700
	n.Detail.CacheCreation.TotalTokens = integer(100)
	n.Detail.CacheCreation.Ephemeral5mInputTokens = integer(25)
	n.Detail.CacheCreation.Ephemeral1hInputTokens = integer(75)
	return n, c
}

func assertNativeMarkerUnknown(t *testing.T, report Report) {
	t.Helper()
	if len(report.Stretches) != 1 {
		t.Fatalf("native primary projection lost its role: %+v", report.Stretches)
	}
	s := report.Stretches[0]
	if s.PrefixRef != "" || !s.ProtectedUntil.IsZero() || s.QualifyingRequests != 0 || s.PriorEligible || !s.UnknownWarmth || !s.Warm(report.AsOf) || !s.ClosedAt.IsZero() || !has(s.Reasons, "no_qualifying_activity") {
		t.Errorf("aggregate native marker activity manufactured entry protection: %+v", s)
	}
	if report.Expected(s.ChatRef, s.TTL).Known || report.WarmBurn.Known || report.WarmBurn.Bounded || report.WarmBurn.UnknownChats != 1 {
		t.Errorf("unknown native warmth became readiness: %+v", report.WarmBurn)
	}
}

func TestNativeMarkerAggregateCannotProvePrefix(t *testing.T) {
	for _, mode := range []string{"managed-1h", "managed-5m", "warming", "unmanaged"} {
		t.Run(mode, func(t *testing.T) {
			ttl := TTL1h
			if mode == "managed-5m" {
				ttl = TTL5m
			}
			n, c := nativeMarkerFixture(ttl)
			if mode == "warming" {
				n.CachePolicy.Selected.Kind = "warming"
			}
			if mode == "unmanaged" {
				n.CachePolicy.Selected = nil
			}
			r := convertNative(t, n, c)
			store, _ := fixture(t)
			put(t, store, r)
			q := query(base.Add(2 * time.Hour))
			q.AccountID = c.AccountID
			report := measure(t, store, q)
			t.Logf("activity=%+v policy=%+v stretches=%+v", r.Activity, r.Policy, report.Stretches)
			if mode == "managed-1h" || mode == "managed-5m" {
				assertNativeMarkerUnknown(t, report)
			}
			if mode == "warming" && len(report.Stretches) != 0 {
				t.Error("unproven warming created a primary stretch")
			}
			if r.Activity.PrimaryPrefix || r.Activity.PrefixRef != "" || r.Activity.ProtectionTTL != "" || !r.Activity.Partial || qualifies(r) {
				t.Errorf("native aggregate tokens manufactured primary-prefix proof: %+v", r.Activity)
			}
			if mode != "unmanaged" && (r.Policy.SelectedTTL != ttl || r.Policy.EffectiveTTL != ttl || r.Policy.Kind != n.CachePolicy.Selected.Kind || r.Kind != n.CachePolicy.Selected.Kind) {
				t.Fatal("marker history or primary/policy role lost", r)
			}
			if counter(r.Usage.CacheCreate5m) != 25 || counter(r.Usage.CacheCreate1h) != 75 || r.Usage.CacheCreate != 100 || !ValueRecord(r, DefaultPriceBook()).Exact() {
				t.Fatal("native exact split/value changed", r.Usage)
			}
			near(t, ValueRecord(r, DefaultPriceBook()).LowUSD(), .007165)
		})
	}
}

