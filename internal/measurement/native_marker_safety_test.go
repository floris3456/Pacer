func TestNativeMarkerLegacyBodyReadGuardAndReplay(t *testing.T) {
	s, db := fixture(t)
	old := frozenNativeMarker(t)
	n, c := nativeMarkerFixture(TTL1h)
	replay := convertNative(t, n, c)
	old.RawUsage = append([]byte(nil), replay.RawUsage...)
	put(t, s, old)
	var compact bytes.Buffer
	if err := json.Compact(&compact, []byte(legacyNativeMarkerBody)); err != nil {
		t.Fatal(err)
	}
	const oldDigest = "85e9d32296d82f956a0d1286de24d25facaaa1862a8d077fc66fa464b541221a"
	if digest(compact.Bytes()) != oldDigest {
		t.Fatal("pre-fix fixture drift")
	}
	// Compare the complete stored row and revision, including identity and raw
	// accounting. Reporting and refused replay must not rewrite any of them.
	readRow := func() []string {
		t.Helper()
		var body, identity, raw, revBody, revRaw []byte
		var revision, received, revReceived int64
		err := db.QueryRow(`SELECT r.body,r.identity,r.raw_usage,r.revision,r.received_at,v.body,v.raw_usage,v.received_at FROM measurement_records r JOIN measurement_record_revisions v ON v.event_id=r.event_id AND v.revision=r.revision WHERE r.event_id=?`, old.EventID).Scan(&body, &identity, &raw, &revision, &received, &revBody, &revRaw, &revReceived)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(body, compact.Bytes()) || digest(body) != oldDigest || !bytes.Equal(body, revBody) || revision != 1 || received != revReceived {
			t.Fatal("canonical legacy body/revision was rewritten")
		}
		return []string{string(body), string(identity), string(raw), string(revBody), string(revRaw), fmt.Sprint(revision, received, revReceived)}
	}
	before := readRow()
	for _, at := range []time.Time{base.Add(20 * time.Minute), base.Add(2 * time.Hour)} {
		q := query(at)
		q.AccountID = old.Attribution.AccountID
		report := measure(t, s, q)
		t.Logf("legacy body sha256=%s as_of=%s projection=%+v", oldDigest, at, report.Stretches)
		assertNativeMarkerUnknown(t, report)
		near(t, report.Stretches[0].Value.LowUSD(), .007165)
	}
	if qualifies(old) {
		t.Error("legacy native Activity accepted as entry proof")
	}
	stored, err := s.Record(ctx, old.EventID, 1)
	if err != nil || !stored.Activity.PrimaryPrefix || stored.Activity.PrefixRef != old.Activity.PrefixRef || stored.Policy.EffectiveTTL != TTL1h {
		t.Fatal("historical fact was erased instead of guarding projection", stored, err)
	}
	// New conversion changes the immutable Activity identity; do not disguise an
	// old callback as a new event/revision or rewrite old evidence to acknowledge it.
	if replay.EventID != old.EventID || replay.Revision != old.Revision || !reflect.DeepEqual(replay.Policy, old.Policy) || !reflect.DeepEqual(replay.Usage, old.Usage) {
		t.Fatal("conversion changed identity, marker policy or accounting")
	}
	if _, err = s.PutRecord(ctx, replay); !errors.Is(err, ErrConflict) {
		t.Errorf("changed immutable callback must retain refusal: %v", err)
	}
	replay.Revision++
	if _, err = s.PutRecord(ctx, replay); !errors.Is(err, ErrConflict) {
		t.Errorf("revision bump rewrote immutable native Activity identity: %v", err)
	}
	if !reflect.DeepEqual(before, readRow()) {
		t.Fatal("report or replay changed frozen storage")
	}
	var revisions int
	if err = db.QueryRow(`SELECT count(*) FROM measurement_record_revisions WHERE event_id=?`, old.EventID).Scan(&revisions); err != nil || revisions != 1 {
		t.Fatal("replay revised immutable history", revisions, err)
	}
}

func TestNativeMarkerUnknownDoesNotExpireAcrossPrimaryRequests(t *testing.T) {
	s, _ := fixture(t)
	for i, id := range []string{"first", "after-false-expiry"} {
		r := warmRecord(id, "chat", base.Add(time.Duration(i)*90*time.Minute), TTL5m, 1)
		r.Native = frozenNativeMarker(t).Native
		// Legacy activity must not select a different TTL from the historical
		// marker policy, much less close the unknown binding at either expiry.
		r.Activity.ProtectionTTL = TTL1h
		put(t, s, r)
	}
	report := measure(t, s, query(base.Add(3*time.Hour)))
	assertNativeMarkerUnknown(t, report)
	if report.Stretches[0].Requests != 2 || report.Stretches[0].TTL != TTL5m {
		t.Fatal("legacy TTL created a false expiry/rebinding", report.Stretches)
	}
}

func TestNativeMarkerLegacyWarmingCannotBuyProtection(t *testing.T) {
	for _, mode := range []string{"alone", "native-primary", "generic-primary", "other-epoch"} {
		t.Run(mode, func(t *testing.T) {
			s, _ := fixture(t)
			primary := warmRecord("primary", "chat", base, TTL1h, 1)
			if mode == "native-primary" {
				primary.Native = frozenNativeMarker(t).Native
				primary.Activity.Partial = true
			}
			warming := primary
			warming.EventID = "warming"
			warming.AttemptID = "warming-attempt"
			warming.RequestID = "warming-request"
			warming.Kind = "warming"
			warming.Policy.Kind = "warming"
			warming.StartedAt = base.Add(30 * time.Minute)
			warming.EndedAt = warming.StartedAt.Add(time.Second)
			warming.Policy.RequestStartedAt = warming.StartedAt
			warming.Native = frozenNativeMarker(t).Native
			if mode == "other-epoch" {
				warming.Policy.ContextEpoch = "new-unproven-epoch"
			}
			if mode != "alone" {
				put(t, s, primary)
			}
			put(t, s, warming)
			report := measure(t, s, query(base.Add(2*time.Hour)))
			if qualifies(warming) {
				t.Error("legacy native warming qualified")
			}
			if mode == "alone" {
				if len(report.Stretches) != 0 {
					t.Fatal("native warming created primary stretch", report.Stretches)
				}
				return
			}
			if mode == "native-primary" {
				assertNativeMarkerUnknown(t, report)
			}
			if len(report.Stretches) != 1 || report.Stretches[0].Requests != 1 || !report.Stretches[0].LastRequestAt.Equal(primary.StartedAt) || report.Stretches[0].ContextEpoch != primary.Policy.ContextEpoch {
				t.Fatal("native warming rebound or extended primary", report.Stretches)
			}
			if mode == "generic-primary" || mode == "other-epoch" {
				st := report.Stretches[0]
				if st.PrefixRef != primary.Activity.PrefixRef || st.QualifyingRequests != 1 || !st.ProtectedUntil.Equal(base.Add(time.Hour)) {
					t.Fatal("native warming bought protection", st)
				}
			}
		})
	}
}

func TestNativeMarkerAuthorityIsIndependentOfPartialFlag(t *testing.T) {
	for _, native := range []bool{false, true} {
		for _, partial := range []bool{false, true} {
			name := "generic"
			if native {
				name = "native"
			}
			if partial {
				name += "-partial"
			}
			t.Run(name, func(t *testing.T) {
				s, _ := fixture(t)
				for i, id := range []string{"one", "two", "three"} {
					r := warmRecord(id, "chat", base.Add(time.Duration(i)*time.Minute), TTL5m, 1)
					r.Activity.Partial = partial
					if native {
						r.Native = frozenNativeMarker(t).Native
					}
					put(t, s, r)
				}
				report := measure(t, s, query(base.Add(time.Hour)))
				if native {
					assertNativeMarkerUnknown(t, report)
					return
				}
				// These generic records explicitly represent qualified executor entry
				// evidence. Partial means a known entry plus an unknown remainder, so
				// its estimated protection timestamp is legitimate but full warmth is not.
				st := report.Stretches[0]
				if st.PrefixRef != "primary-prefix" || st.QualifyingRequests != 3 || !st.ProtectedUntil.Equal(base.Add(7*time.Minute)) || st.UnknownWarmth != partial || st.PriorEligible == partial {
					t.Fatal("generic entry-evidence contract changed", st)
				}
				if partial && !st.Warm(report.AsOf) {
					t.Fatal("unknown remainder lost sticky warmth", st)
				}
			})
		}
	}
}
